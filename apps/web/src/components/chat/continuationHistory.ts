import type { OrchestrationV2ProjectedTurnItem } from "@t3tools/contracts";
import { collectComposerPromptInlineTokens } from "../../composer-editor-mentions";
import { parseHandoffPath } from "./contextHandoff";

export const CONTINUATION_QUOTE_LIMIT = 1500;

/**
 * Quoted history must stay inert. The composer turns `$skill`, `@path`, `[file](path)`,
 * citations and context references into live tokens (and Claude rewrites a trailing `$skill`
 * into a slash command), so the composer's own parser finds them in prose and they are
 * defused: skills/mentions/file links get backticks, links become plain labels. Fenced and
 * inline code is left byte-for-byte unchanged.
 */
export function neutralizeQuotedTokens(text: string) {
  return text
    .split(/(```[\s\S]*?(?:```|$)|`[^`\n]*`)/u)
    .map((part, index) => (index % 2 === 1 ? part : neutralizeProse(part)))
    .join("");
}

function neutralizeProse(prose: string) {
  // Trailing space lets tokens at the very end match, as they would once sent.
  const tokens = collectComposerPromptInlineTokens(`${prose} `).filter(
    (token) => token.end <= prose.length,
  );
  let out = prose;
  for (const token of tokens.toSorted((a, b) => b.start - a.start)) {
    const source = prose.slice(token.start, token.end);
    const inert =
      token.type === "citation"
        ? "[引用]"
        : token.type === "context-reference"
          ? "[上下文引用]"
          : `\`${source}\``;
    out = out.slice(0, token.start) + inert + out.slice(token.end);
  }
  return out;
}

export function continuationQuote(
  text: string,
  title: string,
  source?: { threadId: string; itemId: string },
) {
  const chars = Array.from(text);
  const clipped = chars.length > CONTINUATION_QUOTE_LIMIT;
  const body = neutralizeQuotedTokens(chars.slice(0, CONTINUATION_QUOTE_LIMIT).join(""));
  // Ids let the agent fetch the full message with t3_thread_read when the quote is clipped.
  const origin = source ? `（threadId: ${source.threadId} · 条目 ${source.itemId}）` : "";
  return `\n\n${body
    .split(/\r?\n/u)
    .map((line) => `> ${line}`)
    .join(
      "\n",
    )}${clipped ? "\n> [已截断]" : ""}\n\n— 原会话《${neutralizeQuotedTokens(title.replace(/[\r\n]/gu, " "))}》${origin}\n\n`;
}

/** The continuation prompt is generated by contextHandoff; arbitrary file links are ignored. */
export function continuationHandoffPath(
  firstUserText: string | undefined,
  lastAssistantText: string | undefined,
) {
  const match = firstUserText?.match(/。先完整读取 (.+)，按其中未完成事项继续；/u);
  return (
    (match ? parseHandoffPath(`HANDOFF: ${match[1]}`) : null) ??
    parseHandoffPath(lastAssistantText ?? "")
  );
}

export function continuationMessages(
  items: readonly OrchestrationV2ProjectedTurnItem[],
  query: string,
) {
  const needle = query.trim().toLocaleLowerCase();
  return items
    .filter(
      (row) =>
        (row.item.type === "user_message" || row.item.type === "assistant_message") &&
        (!needle || row.item.text.toLocaleLowerCase().includes(needle)),
    )
    .toSorted((a, b) => a.position - b.position);
}
